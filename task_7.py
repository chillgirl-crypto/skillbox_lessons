""" Задача 8. Т9
Что нужно сделать
У нас есть кнопочный телефон (например, знаменитая Nokia 3310), и мы хотим,

чтобы пользователь мог проще отправлять СМС. Реализуем своего собственного клавиатурного помощника.

Каждой цифре телефона соответствует набор букв:

2 — a, b, c;
3 — d, e, f;
4 — g, h, i;
5 — j, k, l;
6 — m, n, o;
7 — p, q, r, s;
8 — t, u, v;
9 — w, x, y, z.
Пользователь нажимает на клавиши, например 22736368, после чего на экране печатается basement.

Напишите функцию my_t9, которая принимает на вход строку, состоящую из цифр 2–9, и возвращает список слов английского языка, которые можно получить из этой последовательности цифр.

Советы и рекомендации
Список слов английского языка есть в файле /usr/share/dict/words . Cкачайте файл, если у вас его нет.
Посмотрите в сторону регулярных выражений.
О Т9 и других экранных клавиатурах читайте в статье «Эволюция экранных клавиатур».
Что оценивается
Решение работает не более чем за O(N). О том, что такое O большое, можно почитать в статьях Big O и «Сложность алгоритмов. Big O. Основы» .
Функция возвращает список всех возможных слов, а не только первое подходящее.


Общие советы и рекомендации
Список атрибутов журналирования
Список директив для форматирования дат """

import re

T9_DICT = {
    '2': 'abc',
    '3': 'def',
    '4': 'ghi',
    '5': 'jkl',
    '6': 'mno',
    '7': 'pqrs',
    '8': 'tuv',
    '9': 'wxyz',
}


def digits_to_regex(digits):
    groups = (f'[{T9_DICT[d]}]' for d in digits)
    return '^' + ''.join(groups) + '$'


def my_t9(digits):
    pattern = re.compile(digits_to_regex(digits))
    results = []
    with open('/usr/share/dict/words') as f:
        for word in f:
            word = word.strip().lower()
            if len(word) == len(digits) and pattern.match(word):
                results.append(word)
    return results


print(my_t9('22736368'))
